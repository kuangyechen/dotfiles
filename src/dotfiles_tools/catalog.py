"""Component choices, separate from Dotter's file mappings."""

import json
import tomllib
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field


def read_toml(path: Path) -> dict:
    with path.open("rb") as stream:
        return tomllib.load(stream)


def string_list(value: object, label: str) -> list[str]:
    if not isinstance(value, list) or any(not isinstance(item, str) for item in value):
        raise ValueError(f"{label} must be a list of strings")
    return value


class CatalogModel(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True, frozen=True, hide_input_in_errors=True)


class Component(CatalogModel):
    purpose: str = Field(min_length=1)
    platforms: list[Literal["macos", "linux"]]
    install: dict[Literal["macos", "linux"], str]
    binaries: list[str] = Field(default_factory=list)
    dotter: list[str] = Field(default_factory=list)
    requires: list[str] = Field(default_factory=list)
    conflicts: list[str] = Field(default_factory=list)


class Profile(CatalogModel):
    platform: Literal["macos", "linux"]
    includes: list[str] = Field(default_factory=list)
    components: list[str] = Field(default_factory=list)


class CatalogData(CatalogModel):
    version: Literal[1]
    core: list[str] = Field(default_factory=list)
    components: dict[str, Component]
    profiles: dict[str, Profile]


class Selection(CatalogModel):
    profile: str
    components: list[str]
    includes: list[str]
    packages: list[str]

    def render(self) -> str:
        # JSON strings/arrays are also valid TOML for these fields.
        return (
            "# Generated by dots profile; review before saving as .dotter/local.toml.\n"
            f"# Profile: {self.profile}\n"
            f"# Components: {', '.join(self.components)}\n"
            f"includes = {json.dumps(self.includes)}\n"
            f"packages = {json.dumps(self.packages)}\n"
        )


class Catalog:
    def __init__(self, repo: Path):
        self.data = CatalogData.model_validate(read_toml(repo / "catalog.toml"))
        self.components = self.data.components
        self.profiles = self.data.profiles

    def select(
        self, profile: str, additions: tuple[str, ...] = (), exclusions: tuple[str, ...] = ()
    ) -> Selection:
        if profile not in self.profiles:
            raise ValueError(f"Unknown profile {profile!r}; choose {', '.join(self.profiles)}")
        spec = self.profiles[profile]
        platform = spec.platform
        names = [
            *self.data.core,
            *spec.components,
            *additions,
        ]
        for name in [*names, *exclusions]:
            if name not in self.components:
                raise ValueError(f"Unknown component {name!r}")
        selected: list[str] = []
        visiting: set[str] = set()

        def include(name: str) -> None:
            if name in selected:
                return
            if name in exclusions:
                raise ValueError(f"Required component {name!r} was excluded")
            if name in visiting:
                raise ValueError(f"Component dependency cycle at {name!r}")
            if name not in self.components:
                raise ValueError(f"Unknown required component {name!r}")
            component = self.components[name]
            if platform not in component.platforms:
                raise ValueError(f"Component {name!r} does not support {platform}")
            if not component.install.get(platform):
                raise ValueError(
                    f"Component {name!r} needs a purpose and {platform} install guidance"
                )
            visiting.add(name)
            for dependency in component.requires:
                include(dependency)
            visiting.remove(name)
            selected.append(name)

        for name in names:
            if name not in exclusions:
                include(name)
        packages: list[str] = []
        for name in selected:
            component = self.components[name]
            for conflict in component.conflicts:
                if conflict in selected:
                    raise ValueError(
                        f"Components {name!r} and {conflict!r} conflict; use --without"
                    )
            for package in component.dotter:
                if package not in packages:
                    packages.append(package)
        return Selection(
            profile=profile,
            components=selected,
            includes=spec.includes,
            packages=packages,
        )
